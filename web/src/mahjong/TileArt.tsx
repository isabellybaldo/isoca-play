export type Paint = { x: number; y: number; width: number; height: number; fill: string };

// One rect per run of a colour, so a full board stays light on the page.
export function runs(rows: string[], left: number, top: number, colourOf: (ch: string) => string): Paint[] {
  return rows.flatMap((row, y) =>
    [...row.matchAll(/([^.])\1*/g)].map((run) => ({
      x: run.index + left,
      y: y + top,
      width: run[0].length,
      height: 1,
      fill: colourOf(run[1]),
    })),
  );
}

// The dark outline with cut corners, the face with its lighter top row, then the rose edge.
function body(face: { top: string; light: string }): Paint[] {
  return [
    { x: 1, y: 0, width: 16, height: 23, fill: OUTLINE },
    { x: 0, y: 1, width: 18, height: 21, fill: OUTLINE },
    { x: 1, y: 1, width: 16, height: 18, fill: face.top },
    { x: 1, y: 1, width: 16, height: 1, fill: face.light },
    { x: 1, y: 20, width: 16, height: 2, fill: EDGE },
    { x: 1, y: 21, width: 16, height: 1, fill: EDGE_SHADOW },
  ];
}

export function Pixels({ paint, width, height, label }: { paint: Paint[]; width: number; height: number; label: string }) {
  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      shapeRendering="crispEdges"
      role="img"
      aria-label={label}
      className="pixels"
    >
      {paint.map((p, i) => (
        <rect key={i} x={p.x} y={p.y} width={p.width} height={p.height} fill={p.fill} />
      ))}
    </svg>
  );
}

// What a screen reader calls a face. The 1 of bamboo is drawn as the panda and the 1 of
// stars as the moon, so those are their names.
const OWN_NAMES: Record<string, string> = { bamboo1: 'Panda', star1: 'Moon' };

export function faceName(face: string): string {
  if (OWN_NAMES[face]) return OWN_NAMES[face];
  const numbered = /^([a-z]+)(\d)$/.exec(face);
  const word = numbered ? numbered[1] : face;
  const name = word.charAt(0).toUpperCase() + word.slice(1);
  return numbered ? `${name} ${numbered[2]}` : name;
}

export function TileArt({ face }: { face: string }) {
  const art = runs(TILE_ART[face] ?? [], 1, 2, (ch) => PIXEL_COLOURS[ch]);
  return <Pixels paint={[...body(IVORY), ...art]} width={SPRITE_WIDTH} height={SPRITE_HEIGHT} label={faceName(face)} />;
}

export function TileBack() {
  const mark = runs(BACK_MARK, 1, 3, () => BACK_COLOUR);
  return <Pixels paint={[...body(ROSE), ...mark]} width={SPRITE_WIDTH} height={SPRITE_HEIGHT} label="face-down tile" />;
}

// The drawing alone, with no tile around it, for a spot too small to hold a whole tile.
export function FaceArt({ face }: { face: string }) {
  return <Pixels paint={runs(TILE_ART[face] ?? [], 0, 0, (ch) => PIXEL_COLOURS[ch])} width={16} height={16} label={faceName(face)} />;
}
