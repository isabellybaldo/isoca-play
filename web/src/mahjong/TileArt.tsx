function Pixels({ rows, label }: { rows: string[]; label: string }) {
  const rects = rows.flatMap((row, y) =>
    // One rect per run of a colour, so a full board stays light on the page.
    [...row.matchAll(/([^.])\1*/g)].map((run) => (
      <rect
        key={`${run.index}-${y}`}
        x={run.index}
        y={y}
        width={run[0].length}
        height={1}
        fill={PIXEL_COLOURS[run[1]]}
      />
    )),
  );
  return (
    <svg
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      role="img"
      aria-label={label}
      className="pixels"
    >
      {rects}
    </svg>
  );
}

export function TileArt({ face }: { face: string }) {
  return <Pixels rows={TILE_ART[face] ?? []} label={face} />;
}

export function TileBack() {
  return <Pixels rows={BACK} label="face-down tile" />;
}
